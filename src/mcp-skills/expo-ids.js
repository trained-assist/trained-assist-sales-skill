// ─────────────────────────────────────────────────────────────────────────────
// Идентичность компании в каталоге (sales-skill#19, C2).
//
// Один контракт на три места, которые обязаны о нём договориться: генератор
// каталога (86-expo-flexi.js), парсер deep-link (92-flexi-sales.js) и проверка
// собранного каталога (88-expo-catalog.js). Пока правило жило в парсере, а id
// рождался в данных, места не совпадали: парсер принимал только \d+, а в
// реальных каталогах числовых id нет вообще.
//
// Что реально лежит в данных (flexi-consulting/exhibitions, CPM Осень 2026):
//   13C56, LNG001, OL001, 21_dot_12, 6a34143181e2ea78990a38f9   — годные
//   13С11 (кириллическая С, U+0421), 14А71                        — неотличимы от
//     годных на глаз, но это другой байт и Telegram их не передаёт
//   13C18/13D19, "13A19, 13A11", "14 B80"                        — компания на
//     нескольких стендах: id склеен из стенда и не является идентификатором
//   ____________                                                    — стенд не
//     разобран, остались одни подчёркивания
//
// Итог: 75 из 655 уникальных id в одном каталоге нельзя передать в ссылке, и
// 129 id продублированы между компаниями (стенд общий). Оба класса дефектов
// ломают сделку, поэтому ловятся на сборке, а не на клике посетителя.
//
// ГРАНИЦА: id должен быть пригоден для Telegram deep-link start-payload, то есть
// [A-Za-z0-9_-]. Расширять этот набор нельзя — Telegram всё равно не доставит
// символы вне него, и ссылка «соберётся», но не сработает.
// ─────────────────────────────────────────────────────────────────────────────

// Стенд — атрибут карточки, а не идентификатор компании: на одном стенде
// бывает несколько участников, и стенд приходит из данных выставки
// («13C18/13D19», кириллические литеры, несколько номеров через запятую).
const LINK_SAFE_ID_RE = /^[A-Za-z0-9][A-Za-z0-9_.-]*$/;

/** Годится ли id для Telegram deep-link и для поиска компании в данных. */
function isLinkSafeId(id) {
  return LINK_SAFE_ID_RE.test(String(id ?? ''));
}

/**
 * Разбор payload deep-link «<eventKey>_deal_<companyId>».
 *
 * eventKey идёт в путь на диске (expoDataDir), поэтому он остаётся уже
 * companyId — только в query-параметр, но тоже строгий: значение приходит по
 * ссылке и участвует в поиске компании, поэтому мусорный символ означал бы
 * молчаливо ненайденную компанию.
 *
 * Подчёркивание внутри companyId разрешено и неоднозначно с разделителем:
 * отличить id «21_dot_12» от «id с хвостом» по строке нельзя, поэтому берём
 * первый _deal_ и требуем от companyId допустимый набор символов. Разбирать
 * «жадным» способом нельзя: eventKey подчёркиваний не содержит.
 */
const DEEP_LINK_RE = /^([a-z0-9][a-z0-9-]*)_deal_([A-Za-z0-9][A-Za-z0-9_.-]*)$/i;

/**
 * @returns {{ eventKey: string, companyId: string }|null}
 */
function parseDeepLink(payload) {
  const m = String(payload || '').trim().match(DEEP_LINK_RE);
  if (!m) return null;
  return { eventKey: m[1], companyId: m[2] };
}

/**
 * Проблемы идентичности в наборе компаний — для падения на сборке каталога.
 * @returns {{ duplicates: Array, unsafe: Array }}
 */
function findIdProblems(companies) {
  const seen = new Map();
  const duplicates = [];
  for (const c of companies || []) {
    const id = String(c?.id ?? '');
    if (seen.has(id)) {
      // Один id у нескольких компаний — «Создать сделку» найдёт первую, и у
      // второй компании сделка будет чужой (74 дубля deal_payload в CPM).
      duplicates.push({ id, first: seen.get(id), second: c?.n || c?.name || '' });
    } else {
      seen.set(id, c?.n || c?.name || '');
    }
  }
  const unsafe = (companies || [])
    .filter(c => !isLinkSafeId(c?.id))
    .map(c => ({ id: String(c?.id ?? ''), company: c?.n || c?.name || '' }));
  return { duplicates, unsafe };
}

module.exports = { LINK_SAFE_ID_RE, isLinkSafeId, DEEP_LINK_RE, parseDeepLink, findIdProblems };